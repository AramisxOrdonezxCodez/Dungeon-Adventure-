package model;

/**
 * Represents the four directions used for dungeon doors and movement.
 *
 * @author Kevin Munoz-Rivera
 * @version 2026-10-29
 */
public enum Direction {

    /** North, toward the top of the dungeon map. */
    NORTH,

    /** South, toward the bottom of the dungeon map. */
    SOUTH,

    /** East, toward the right side of the dungeon map. */
    EAST,

    /** West, toward the left side of the dungeon map. */
    WEST
}
